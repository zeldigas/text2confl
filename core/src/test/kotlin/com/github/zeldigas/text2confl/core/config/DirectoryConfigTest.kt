class DirectoryConfigTest {
    @Test
    fun `Properly read from file`(@TempDir dir: Path) {
        dir.resolve(".text2confl.yml").writeText(
            DirectoryConfig::class.java.getResourceAsStream("/data/.text2confl.yml")!!.reader().readText()
        )
        val config = readDirectoryConfig(dir)

        assertThat(config).isEqualTo(
            DirectoryConfig(
                server = "https://example.com",
                space = "TEST",
                defaultParentId = "1",
                defaultParent = "Parent",
                removeOrphans = Cleanup.None,
                notifyWatchers = false,
                titlePrefix = "a",
                titlePostfix = "b",
                editorVersion = EditorVersion.V1,
                modificationCheck = ChangeDetector.CONTENT,
                docsLocation = "test",
                addAutogeneratedNote = false,
                autogeneratedNote = "test",
                client = HttpClientParams(
                    skipSsl = true,
                ),
                codeBlocks = CodeBlockParams("foo", mapOf("aa" to "js")),
                markdown = MarkdownParams(
                    anyMacro = true,
                    enabledMacros = listOf("abc"),
                    emoji = true,
                    diagrams = MarkdownDiagramParameters(
                        tempDir = true,
                        baseDir = "abc",
                        mermaid = MermaidDiagramsConfiguration(
                            enabled = false,
                            defaultFormat = "svg",
                            executable = "mmm",
                            configFile = "file",
                            cssFile = "css",
                            puppeeterConfig = "pc"
                        ),
                        plantuml = PlantUmlDiagramsConfiguration(
                            enabled = false,
                            executable = "pu",
                            defaultFormat = "svg"
                        ),
                        kroki = KrokiDiagramsConfiguration(
                            enabled = false,
                            server = URI.create("https://example.org"),
                            defaultFormat = "svg"
                        )
                    ),
                    autoLinks = false,
                    tables = TablesConfiguration(
                        columnSpans = false,
                        discardExtraColumns = false,
                        appendMissingColumns = false,
                        headerSeparatorColumnMatch = false
                    ),
                    typography = TypographyConfiguration(quotes = true, smarts = false)
                ),
                asciidoc = AsciidocParams(
                    gems = listOf("a"),
                    diagrams = AsciidocDiagrams.None,
                    bundledMacros = false,
                    attributes = mapOf("toclevels" to 5),
                    tempDir = true,
                    baseDir = "b",
                    kroki = KrokiDiagramsParameters(
                        server = URI.create("https://example.org"),
                        fetch = false,
                        defaultFormat = "png"
                    )
                )
            )
        )
    }

    @Test
    fun `YAML aliases are resolved for scalars and mappings`(@TempDir dir: Path) {
        dir.resolve(".text2confl.yml").writeText(
            """
            x-shared:
              lang-mapping: &lang-mapping
                aa: js
                bb: kotlin
            title-prefix: &affix "[docs] "
            title-postfix: *affix
            code-blocks:
              extra-mapping: *lang-mapping
            """.trimIndent()
        )
        val config = readDirectoryConfig(dir)

        assertThat(config.titlePrefix).isEqualTo("[docs] ")
        assertThat(config.titlePostfix).isEqualTo("[docs] ")
        assertThat(config.codeBlocks.extraMapping).isEqualTo(mapOf("aa" to "js", "bb" to "kotlin"))
    }

    @Test
    fun `YAML merge key with a single alias is resolved, explicit keys win`(@TempDir dir: Path) {
        dir.resolve(".text2confl.yml").writeText(
            """
            x-shared:
              lang-mapping: &lang-mapping
                aa: js
                bb: java
              client: &client
                skip-ssl: true
            code-blocks:
              extra-mapping:
                <<: *lang-mapping
                bb: kotlin
            client:
              <<: *client
            """.trimIndent()
        )
        val config = readDirectoryConfig(dir)

        assertThat(config.codeBlocks.extraMapping).isEqualTo(mapOf("aa" to "js", "bb" to "kotlin"))
        assertThat(config.client).isEqualTo(HttpClientParams(skipSsl = true))
    }

    @Test
    fun `YAML merge key with a list of aliases is rejected`(@TempDir dir: Path) {
        dir.resolve(".text2confl.yml").writeText(
            """
            x-shared:
              first: &first
                aa: js
              second: &second
                bb: kotlin
            code-blocks:
              extra-mapping:
                <<: [*first, *second]
            """.trimIndent()
        )

        assertFailure { readDirectoryConfig(dir) }
            .isInstanceOf<JsonMappingException>()
            .messageContains("'<<'")
    }

    @Test
    fun `Diagram macros are read from file`(@TempDir dir: Path) {
        dir.resolve(".text2confl.yml").writeText(
            """
            x-templates:
              macro: &macro >-
                <macro lang="{{lang}}">{{#cdata}}{{{source}}}{{/cdata}}</macro>
            markdown:
              diagrams:
                macros:
                  plantuml:
                    formats: [puml, plantuml]
                    template: *macro
                  mermaid:
                    formats:
                      - mermaid
                    template: *macro
            """.trimIndent()
        )

        val config = readDirectoryConfig(dir)

        val template = "<macro lang=\"{{lang}}\">{{#cdata}}{{{source}}}{{/cdata}}</macro>"
        val expected = mapOf(
            "plantuml" to DiagramMacroConfiguration(listOf("puml", "plantuml"), template),
            "mermaid" to DiagramMacroConfiguration(listOf("mermaid"), template),
        )
        assertThat(config.markdown.diagrams.macros).isEqualTo(expected)
        assertThat(config.markdown.toConfig(dir).diagrams.macros).isEqualTo(expected)
    }

    @Test
    fun `Conversion of directory inputs to asciidoctor parameters for asciidoctor diagrams`() {
        val dirAsciidoc = AsciidocParams(
            gems = listOf("extra"),
            diagrams = AsciidocDiagrams.Diagrams,
            bundledMacros = true,
            attributes = mapOf("toclevels" to 5),
            tempDir = false,
            baseDir = "test",
            kroki = KrokiDiagramsParameters(
                server = URI.create("https://example.org"),
                fetch = true,
                defaultFormat = "png"
            )
        )

        val baseDir = Path(".")
        assertThat(dirAsciidoc.toConfig(baseDir)).isEqualTo(AsciidoctorConfiguration(
            libsToLoad = listOf("extra", "asciidoctor-diagram"),
            loadBundledMacros = true,
            attributes = mapOf(
                "toclevels" to 5
            ),
            workdir = baseDir.resolve(Path("test"))
        ))
    }

    @Test
    fun `Conversion of directory inputs to asciidoctor parameters for kroki diagrams`() {
        val dirAsciidoc = AsciidocParams(
            gems = listOf("extra"),
            diagrams = AsciidocDiagrams.Kroki,
            bundledMacros = true,
            attributes = mapOf("toclevels" to 5),
            tempDir = false,
            baseDir = "test",
            kroki = KrokiDiagramsParameters(
                server = URI.create("https://example.org"),
                fetch = true,
                defaultFormat = "png"
            )
        )

        val baseDir = Path(".")
        assertThat(dirAsciidoc.toConfig(baseDir)).isEqualTo(AsciidoctorConfiguration(
            libsToLoad = listOf("extra", "asciidoctor-kroki"),
            loadBundledMacros = true,
            attributes = mapOf(
                "kroki-server-url" to "https://example.org",
                "kroki-default-format" to "png",
                "kroki-fetch-diagram" to "true",
                "toclevels" to 5
            ),
            workdir = baseDir.resolve(Path("test"))
        ))
    }
}